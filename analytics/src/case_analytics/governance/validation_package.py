"""Render an independent model-validation package (Markdown)."""

from __future__ import annotations

from typing import Any

import pandas as pd

from case_analytics.features.policy import FeaturePolicy

LIMITATIONS = [
    "Training and evaluation data are synthetic; labels are policy-derived from the generator, not observed loan outcomes.",
    "Bad-rate and expected-loss figures are proxies (fraud among approved x loan amount x assumed loss-given-fraud).",
    "Application metadata fraud signals are synthetic and separable by construction (fraud_signal_rate governs prevalence).",
    "Sensitive attributes are synthetic scenario labels; fairness results are technical controls, not legal findings.",
    "No property, appraisal, LTV or co-borrower modelling; loan amount is a fixed multiple of stated income.",
    "Out-of-time and stress splits are simulated regime shifts, not observed market history.",
]


def _fmt(x: Any, d: int = 3) -> str:
    if x is None:
        return "n/a"
    if isinstance(x, float):
        return f"{x:.{d}f}"
    return str(x)


def _table(rows: list[dict[str, Any]], cols: list[str]) -> str:
    if not rows:
        return "_none_\n"
    head = "| " + " | ".join(cols) + " |\n|" + "---|" * len(cols) + "\n"
    body = "".join("| " + " | ".join(_fmt(r.get(c)) for c in cols) + " |\n" for r in rows)
    return head + body


def render_validation_package(
    *,
    champion: dict[str, Any],
    models: list[dict[str, Any]],
    lineage: dict[str, Any],
    feature_names: list[str],
    policy: FeaturePolicy,
    fairness: dict[str, Any],
    importance: pd.DataFrame,
    findings: list[dict[str, Any]],
    approval: dict[str, Any] | None,
    economics: dict[str, Any],
    monitoring: dict[str, Any],
) -> str:
    L: list[str] = []
    L.append(f"# Model Validation Package: {champion['model']} v{champion['version']}\n")
    L.append("## 1. Model purpose\n")
    L.append(
        "Score mortgage applications for the probability that the application contains injected "
        "misrepresentation or manipulation (income, employment, assets, liabilities, identity, documents, "
        "occupancy, gift funds, asset seasoning, straw buyer). The score drives alert generation and manual-review "
        "routing; it is not a standalone decline reason. Adverse-action reasons come from the governed reason-code "
        "catalog via the SHAP-to-reason-code mapping and the rule engine.\n"
    )
    L.append("## 2. Intended users\n")
    L.append(
        "Fraud strategy, underwriting operations, model risk management (validation), and internal audit.\n"
    )
    L.append("## 3. Population and exclusions\n")
    tr = lineage.get("splits", {}).get("train", {})
    L.append(
        f"Synthetic single-borrower mortgage purchase/refinance applications generated by Case Explorer "
        f"(generator {lineage.get('generator_version')}, baseline regime, as-of {tr.get('as_of_date')}). "
        f"Training records: {tr.get('record_count')} with fraud rate {_fmt(tr.get('fraud_rate'))}. "
        "The INCOHERENT data-quality negative control is labelled non-fraud. No real customer data is used.\n"
    )
    L.append("## 4. Dataset lineage\n")
    L.append(
        _table(
            [{"split": k, **v} for k, v in lineage.get("splits", {}).items()],
            [
                "split",
                "population_regime",
                "record_count",
                "fraud_rate",
                "seed",
                "configuration_hash",
                "file_sha256",
            ],
        )
    )
    L.append(
        f"\nDataset version {lineage.get('dataset_version')}, generator commit `{lineage.get('generator_commit')}`, "
        f"feature schema {lineage.get('feature_schema_version')}, feature policy {lineage.get('feature_policy_version')}, "
        f"ruleset {lineage.get('ruleset_version')}.\n"
    )
    L.append("## 5. Feature definitions\n")
    L.append(
        _table(
            [{"feature": f, "policy_class": policy.classify(f)} for f in feature_names],
            ["feature", "policy_class"],
        )
    )
    L.append(
        "\nSensitive attributes (age, region, income band, persona, family-status and disability-income scenarios) are "
        "excluded from model inputs by the feature policy and used only in section 10.\n"
    )
    L.append("## 6. Methodology\n")
    L.append(
        "Four strategies were trained on identical permitted features: a deterministic rules baseline mirroring the "
        "production fraud ruleset, L2 logistic regression (standardised, class-balanced), a random forest, and gradient "
        f"boosting ({champion.get('backend')} backend for the champion). Thresholds were tuned on the validation split "
        "to maximise F1 subject to a 5% false-positive-rate ceiling; the EV-optimal threshold from the decision-economics "
        "simulator is reported alongside. Held-out test, out-of-time, geography-stress, economic-regime-stress, "
        "adversarial and clean-negative-control splits were scored once, after tuning.\n"
    )
    L.append("## 7. Assumptions\n")
    L.append(
        "- Claim-vs-evidence discrepancies observed at application time are available at scoring time.\n"
        "- Evidence documents are trustworthy except where the generator injects tampering.\n"
        "- Loss-given-fraud and review costs in the economics module are configurable assumptions, not measured values.\n"
        "- Label semantics follow the generator policy (non-material variances are review, not fraud declines).\n"
    )
    L.append("## 8. Performance\n")
    L.append(
        _table(
            [
                {
                    "model": m["model"],
                    **{
                        k: m["test"].get(k)
                        for k in ("pr_auc", "roc_auc", "precision", "recall", "f1", "fpr", "ece", "brier")
                    },
                }
                for m in models
            ],
            ["model", "pr_auc", "roc_auc", "precision", "recall", "f1", "fpr", "ece", "brier"],
        )
    )
    L.append("\nChampion by split:\n")
    L.append(
        _table(
            [{"split": k, **v} for k, v in champion.get("splits", {}).items()],
            ["split", "n", "fraud_n", "pr_auc", "roc_auc", "recall", "fpr", "ece"],
        )
    )
    L.append("\nRecall by fraud type (test):\n")
    L.append(_table(champion.get("by_fraud_type", []), ["group", "n", "fraud_n", "recall", "alert_rate"]))
    L.append("## 9. Calibration\n")
    L.append(
        f"Expected calibration error on test: {_fmt(champion['test'].get('ece'))}; Brier score: "
        f"{_fmt(champion['test'].get('brier'))}. See calibration.png.\n"
    )
    L.append("## 10. Robustness\n")
    oot = champion.get("out_of_time", {})
    adv = champion.get("adversarial", {})
    L.append(
        f"Out-of-time PR-AUC {_fmt(oot.get('pr_auc'))} (recall {_fmt(oot.get('recall'))}, FPR {_fmt(oot.get('fpr'))}); "
        f"adversarial PR-AUC {_fmt(adv.get('pr_auc'))} (recall {_fmt(adv.get('recall'))}); "
        f"clean-control FPR {_fmt(champion.get('clean_control_fpr'))}.\n"
    )
    hi = {k: v.get("features_high_drift", []) for k, v in monitoring.get("splits", {}).items()}
    L.append(
        "High-drift features (PSI >= 0.25) by split: "
        + "; ".join(f"{k}: {', '.join(v) or 'none'}" for k, v in hi.items())
        + "\n"
    )
    L.append("## 11. Fairness\n")
    L.append(f"> {fairness.get('disclaimer')}\n")
    cf = fairness.get("counterfactual", {})
    L.append(
        f"Status: **{fairness.get('status')}**. Counterfactual pairs {cf.get('pairs')}, changed {cf.get('changed')}, "
        f"invariance {_fmt(cf.get('invariance_rate'))}. Significant independent-attribute disparities: "
        f"{len(fairness.get('significant_independent_disparities', []))}. Proxy flags: {len(fairness.get('proxy_flags', []))}.\n"
    )
    L.append(
        _table(
            fairness.get("subgroups", [])[:40],
            [
                "attribute",
                "group",
                "n",
                "approval_rate",
                "selection_ratio_vs_pooled",
                "alert_rate",
                "fpr",
                "fnr",
                "approval_p_value",
            ],
        )
    )
    L.append("## 12. Explainability\n")
    top = (
        [{str(k): v for k, v in r.items()} for r in importance.head(10).to_dict(orient="records")]
        if len(importance)
        else []
    )
    L.append(
        _table(
            top,
            [
                c
                for c in ("feature", "permutation_importance", "native_importance", "coefficient")
                if c in importance.columns
            ],
        )
    )
    L.append(
        "\nLocal SHAP explanations are mapped to governed reason codes with their evidence sources (see model-summary.json).\n"
    )
    L.append("## 13. Decision economics\n")
    L.append(
        f"EV-optimal threshold {_fmt(economics.get('ev_optimal_threshold'), 2)} versus F1/FPR-tuned threshold "
        f"{_fmt(champion.get('threshold'), 2)}; net expected benefit at the selected threshold "
        f"{_fmt(economics.get('net_benefit_at_selected'), 0)} (see threshold-economics.csv).\n"
    )
    L.append("## 14. Limitations\n")
    L.extend(f"- {x}\n" for x in LIMITATIONS)
    L.append("## 15. Findings\n")
    L.append(_table(findings, ["finding_id", "severity", "title", "detail", "remediation_status"]))
    L.append("## 16. Remediation status\n")
    open_n = sum(1 for f in findings if f.get("remediation_status") == "OPEN")
    L.append(f"{open_n} open finding(s) of {len(findings)}.\n")
    L.append("## 17. Approval decision\n")
    if approval:
        L.append(f"APPROVED by {approval['approver']} at {approval['at']}: {approval['reason']}\n")
    else:
        L.append("Not approved.\n")
    return "\n".join(L)
